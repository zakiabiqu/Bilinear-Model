test_that("input checks give informative errors", {
  x <- as.numeric(log10(lynx))
  expect_error(bilinear(c(1, NA, 2), ar = 1), "missing")
  expect_error(bilinear(x, ar = 0), "positive")
  expect_error(bilinear(x, bl = list(c(1, 2, 3))), "pair")
  expect_error(bilinear(x, ar = 3, gamma = 2), "gamma")
  expect_error(bilinear(x, ar = 1, start = 1), "length")
})

test_that("methods return the expected structure", {
  fit <- bilinear(log10(lynx), ar = c(1, 2), ma = 1, bl = c(1, 1))
  expect_s3_class(fit, "bilinear")
  expect_named(coef(fit), c("a1", "a2", "c1", "b(1,1)", "alpha"))
  expect_equal(dim(vcov(fit)), c(5, 5))
  s <- summary(fit)
  expect_s3_class(s, "summary.bilinear")
  expect_equal(nrow(s$diagnostics), 5)
  expect_output(print(s), "Invertibility")
  fc <- predict(fit, n.ahead = 3, nsim = 500, seed = 1)
  expect_s3_class(fc, "bilinear_forecast")
  expect_length(fc$pred, 3)
  expect_true(all(fc$lower[, "95%"] <= fc$upper[, "95%"]))
  expect_equal(start(fc$pred)[1], 1935)
})
